// Scales that aren't powers of 2, so that a zoom computed with log2 is wrong.
final _proj4 = Proj4Crs.fromFactory(
  code: 'EPSG:3978',
  proj4Projection: proj4.Projection.add(
    'EPSG:3978',
    '+proj=lcc +lat_0=49 +lon_0=-95 +lat_1=49 +lat_2=77 +x_0=0 +y_0=0 '
        '+ellps=GRS80 +units=m +no_defs',
  ),
  resolutions: const [5000, 2500, 1000, 500, 250, 100],
);

class _Map {
  final String name;
  final Crs crs;
  final LatLng center;
  final double zoom;
  final double minZoom;
  final double maxZoom;

  const _Map(
    this.name,
    this.crs,
    this.center,
    this.zoom, {
    required this.minZoom,
    required this.maxZoom,
  });

  LatLngBounds get bounds => LatLngBounds(
        LatLng(center.latitude - 0.3, center.longitude - 0.5),
        LatLng(center.latitude + 0.4, center.longitude + 0.6),
      );

  List<LatLng> get coordinates => [
        LatLng(center.latitude - 0.25, center.longitude - 0.4),
        LatLng(center.latitude + 0.3, center.longitude - 0.3),
        LatLng(center.latitude + 0.2, center.longitude + 0.5),
        LatLng(center.latitude - 0.1, center.longitude + 0.35),
        center,
      ];
}

final _maps = [
  const _Map(
    'EPSG:3857',
    Epsg3857(),
    LatLng(45.5, -122.6),
    10,
    minZoom: 10.5,
    maxZoom: 8.5,
  ),
  _Map(
    'Proj4Crs',
    _proj4,
    const LatLng(45.4, -75.7),
    3,
    minZoom: 4.6,
    maxZoom: 3.5,
  ),
];

const _paddings = [
  ('no padding', EdgeInsets.zero),
  ('padding', EdgeInsets.fromLTRB(10, 20, 30, 40)),
];

typedef _Options = ({
  double minZoom,
  double? maxZoom,
  bool forceIntegerZoomLevel,
});

List<(String, _Options)> _options(_Map map) => [
      (
        'default',
        (minZoom: 0, maxZoom: null, forceIntegerZoomLevel: false),
      ),
      (
        'integer zoom',
        (minZoom: 0, maxZoom: null, forceIntegerZoomLevel: true),
      ),
      (
        'minimum zoom',
        (minZoom: map.minZoom, maxZoom: null, forceIntegerZoomLevel: false),
      ),
      (
        'maximum zoom',
        (minZoom: 0, maxZoom: map.maxZoom, forceIntegerZoomLevel: false),
      ),
    ];

CameraFit _fit(String kind, _Map map, EdgeInsets padding, _Options o) =>
    switch (kind) {
      'bounds' => CameraFit.bounds(
          bounds: map.bounds,
          padding: padding,
          minZoom: o.minZoom,
          maxZoom: o.maxZoom,
          forceIntegerZoomLevel: o.forceIntegerZoomLevel,
        ),
      'coordinates' => CameraFit.coordinates(
          coordinates: map.coordinates,
          padding: padding,
          minZoom: o.minZoom,
          maxZoom: o.maxZoom ?? double.infinity,
          forceIntegerZoomLevel: o.forceIntegerZoomLevel,
        ),
      _ => CameraFit.insideBounds(
          bounds: map.bounds,
          padding: padding,
          minZoom: o.minZoom,
          maxZoom: o.maxZoom,
          forceIntegerZoomLevel: o.forceIntegerZoomLevel,
        ),
    };

void main() {
  var i = 0;
  for (final map in _maps) {
    for (final rotation in [0.0, 30.0, 200.0]) {
      for (final (paddingName, padding) in _paddings) {
        for (final (optionsName, options) in _options(map)) {
          for (final kind in ['bounds', 'coordinates', 'inside bounds']) {
            final expected = _expected[i++];
            test(
                '${map.name}, rotation $rotation, $paddingName, $optionsName, '
                '$kind', () {
              final camera = MapCamera(
                crs: map.crs,
                center: map.center,
                zoom: map.zoom,
                rotation: rotation,
                nonRotatedSize: const Size(400, 600),
              );
              final fitted = _fit(kind, map, padding, options).fit(camera);
              expect(fitted.pitch, 0);
              expect(fitted.rotation, rotation);
              expect(fitted.zoom, closeTo(expected.$1, 1e-3));
              final distance = (fitted.projectAtZoom(fitted.center) -
                      fitted.projectAtZoom(LatLng(expected.$2, expected.$3)))
                  .distance;
              expect(distance, lessThan(0.1));
              if (kind != 'inside bounds' && optionsName != 'minimum zoom') {
                final area = padding
                    .deflateRect(Offset.zero & camera.nonRotatedSize)
                    .inflate(0.01);
                final points = kind == 'bounds'
                    ? [
                        map.bounds.northWest,
                        map.bounds.northEast,
                        map.bounds.southEast,
                        map.bounds.southWest,
                      ]
                    : map.coordinates;
                for (final point in points) {
                  expect(
                    area.contains(fitted.latLngToScreenOffset(point)),
                    isTrue,
                  );
                }
              }
            });
          }
        }
      }
    }
  }
}

